async function main() {
  for (const parent of categoryTree) {
    const parentSlug = slugify(parent.name);
    const upsertedParent = await prisma.category.upsert({
      where: { slug: parentSlug },
      update: { name: parent.name },
      create: { name: parent.name, slug: parentSlug },
    });
    console.log(`✅ ${upsertedParent.name} (${upsertedParent.slug})`);

    for (const childName of parent.children) {
      const childSlug = slugify(childName);
      await prisma.category.upsert({
        where: { slug: childSlug },
        update: { name: childName, parentId: upsertedParent.id },
        create: { name: childName, slug: childSlug, parentId: upsertedParent.id },
      });
      console.log(`   └─ ${childName} (${childSlug})`);
    }
  }
  console.log('\n🎉 Категории успешно добавлены/обновлены');
}

